QString AClipboardDriverMacOS::mTextPaste(void) {

	QString oOutput = "";

	NSPasteboard* oPasteboard = [NSPasteboard generalPasteboard];
	NSArray<NSPasteboardType>* oTextTypes = @[NSPasteboardTypeString];

	BOOL isExplicitText = [oPasteboard canReadItemWithDataConformingToTypes:oTextTypes];
	if (isExplicitText) {
		_A_DEBUG << "Extracting standard plain text";
		NSString* oNSString = [oPasteboard stringForType:NSPasteboardTypeString];
		if (oNSString != nil) oOutput = QString::fromUtf8([oNSString UTF8String]);
	}

	return oOutput;
}


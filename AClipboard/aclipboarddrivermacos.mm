	\fn

	Doc.
*/

void fAClipboardDriverMacOS_TextCopyPrivate(QString& inText) {

	if (inText.isEmpty()) return;

	NSPasteboard* oPasteboard = [NSPasteboard generalPasteboard];

	@autoreleasepool {

		NSString* oNSText = [NSString stringWithCharacters:(const unichar*)inText.unicode() length:inText.length()];

		NSArray* oTypes = @[
			NSPasteboardTypeString,
			@"org.nspasteboard.ConcealedType",
			@"org.nspasteboard.AutoGeneratedType"
		];

		[oPasteboard clearContents];
		[oPasteboard declareTypes:oTypes owner:nil];
		[oPasteboard setString:oNSText forType:NSPasteboardTypeString];
		[oPasteboard setString:@"" forType:@"org.nspasteboard.ConcealedType"];
		[oPasteboard setString:@"" forType:@"org.nspasteboard.AutoGeneratedType"];

		_A_DEBUG << "Private text copied to clipboard";
	}

	QChar* data = inText.data();
	for (int i = 0; i < inText.length(); ++i) {
		data[i] = QChar(0);
	}
	inText.clear();
	inText.squeeze();
}



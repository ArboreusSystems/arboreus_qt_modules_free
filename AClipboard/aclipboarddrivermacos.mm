/*!
	\fn

	Doc.
*/

void fAClipboardDriverMacOS_TextCopyPrivateAndClear(QString& inText, int inTimeSeconds) {

	fAClipboardDriverMacOS_TextCopyPrivate(inText);
	fAClipboardDriverMacOS_ClearAfter(inTimeSeconds);
}


// -----------
/*!
	\fn

	Doc.
*/

void fAClipboardDriverMacOS_Clear(void) {

	if (gClearTimer && gClearTimer->isActive()) {
		gClearTimer->stop();
		_A_DEBUG << "Previous pending clearing task canceled";
	}

	NSPasteboard* oPasteboard = [NSPasteboard generalPasteboard];

	@autoreleasepool {

		[oPasteboard clearContents];

		NSPasteboardItem* oItem = [[NSPasteboardItem alloc] init];
		[oItem setString:@"" forType:@"org.nspasteboard.TransientType"];
		[oItem setString:@"" forType:@"org.nspasteboard.ConcealedType"];
		[oItem setString:@"" forType:@"com.apple.is-remote-pasteboard-item"];
		[oPasteboard writeObjects:@[oItem]];

		[oPasteboard clearContents];
	}

	_A_DEBUG << "Clipboard cleared";
}


// -----------
/*!
	\fn

	Doc.
*/

void fAClipboardDriverMacOS_ClearAfter(int inTimeSeconds) {

	if (gClearTimer && gClearTimer->isActive()) {
		gClearTimer->stop();
		_A_DEBUG << "Previous pending clearing task canceled";
	}

	if (!gClearTimer) {
		gClearTimer = new QTimer(qApp);
		gClearTimer->setSingleShot(true);
	}

	QObject::disconnect(gClearTimer,&QTimer::timeout,nullptr,nullptr);

	QObject::connect(gClearTimer,&QTimer::timeout,[]() {
		fAClipboardDriverMacOS_Clear();
	});

	gClearTimer->start(inTimeSeconds * 1000);
}


